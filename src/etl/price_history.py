"""
FinTech AI - seeded synthetic daily price history (SYNTHETIC DATA).

Generates ~504 trading days of daily returns for every ticker in
data/portfolio.json with a one-factor-plus-sector structure and fat tails:

    r_i,t = beta_i * m_t + s_sector(i),t + e_i,t

    m_t  ~ market factor, Student-t(df=4) scaled to MARKET_DAILY_VOL
    s_t  ~ sector factor, Student-t(df=4) scaled to SECTOR_DAILY_VOL
    e_t  ~ idiosyncratic, Student-t(df=4) scaled to IDIO_DAILY_VOL

beta_i is the position's beta from portfolio.json. Prices are built
backwards so that the final price equals each position's current_price.
Parameters were fixed before any backtest was run and are recorded in the
output file. Nothing here is real market data.
"""

from __future__ import annotations

import datetime as dt
import json
import math

import numpy as np

SEED = 20260319
N_DAYS = 504
T_DF = 4
MARKET_DAILY_VOL = 0.010
SECTOR_DAILY_VOL = 0.005
IDIO_DAILY_VOL = 0.012


def _scaled_t(rng: np.random.Generator, size, vol: float) -> np.ndarray:
    # Var(t_df) = df / (df - 2); rescale to unit variance, then to vol.
    return rng.standard_t(T_DF, size=size) * vol / math.sqrt(T_DF / (T_DF - 2))


def _business_days_ending(end: dt.date, n: int) -> list:
    days = []
    d = end
    while len(days) < n:
        if d.weekday() < 5:
            days.append(d)
        d -= dt.timedelta(days=1)
    return [x.isoformat() for x in reversed(days)]


def generate_price_history(portfolio: dict, n_days: int = N_DAYS, seed: int = SEED) -> dict:
    rng = np.random.default_rng(seed)
    positions = portfolio["positions"]
    sectors = sorted({p["sector"] for p in positions})

    market = _scaled_t(rng, n_days, MARKET_DAILY_VOL)
    sector_f = {s: _scaled_t(rng, n_days, SECTOR_DAILY_VOL) for s in sectors}

    as_of = dt.date.fromisoformat(portfolio["as_of_date"])
    dates = _business_days_ending(as_of, n_days + 1)  # n_days returns need n_days+1 prices

    tickers = {}
    for p in positions:
        idio = _scaled_t(rng, n_days, IDIO_DAILY_VOL)
        raw = p["beta"] * market + sector_f[p["sector"]] + idio
        raw = np.maximum(raw, -0.95)  # a price can't fall below zero
        prices = np.empty(n_days + 1)
        prices[-1] = p["current_price"]
        for t in range(n_days - 1, -1, -1):
            prices[t] = prices[t + 1] / (1.0 + raw[t])
        prices = np.round(prices, 4)
        prices[-1] = p["current_price"]
        returns = prices[1:] / prices[:-1] - 1.0  # returns implied by the stored prices
        tickers[p["ticker"]] = {
            "sector": p["sector"],
            "beta_input": p["beta"],
            "prices": [float(x) for x in prices],
            "returns": [round(float(x), 8) for x in returns],
        }

    return {
        "synthetic": True,
        "description": (
            "SYNTHETIC daily price history generated by src/etl/price_history.py "
            "(scripts/generate_price_history.py). Not real market data."
        ),
        "generator": {
            "seed": seed,
            "n_return_days": n_days,
            "distribution": f"Student-t df={T_DF}, variance-normalised",
            "market_daily_vol": MARKET_DAILY_VOL,
            "sector_daily_vol": SECTOR_DAILY_VOL,
            "idio_daily_vol": IDIO_DAILY_VOL,
            "model": "r_i,t = beta_i * m_t + s_sector,t + e_i,t",
            "anchored_to": "portfolio.json current_price on as_of_date",
        },
        "as_of_date": portfolio["as_of_date"],
        "dates": dates,
        "market_factor_returns": [round(float(x), 8) for x in market],
        "tickers": tickers,
    }


def write_price_history(path: str, portfolio: dict) -> dict:
    data = generate_price_history(portfolio)
    with open(path, "w") as f:
        json.dump(data, f, separators=(",", ":"))
        f.write("\n")
    return data
