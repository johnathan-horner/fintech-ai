"""
FinTech AI - eval dataset (data/eval/fintech_eval.jsonl).

Reference answers are COMPUTED from the bundled data by the code below
(never typed by hand). Each item has a deterministic dev/heldout split
(seeded shuffle within each component, 50/50).

Split (documented): items are grouped by component and sorted by id; each group is shuffled with
random.Random(f"{SPLIT_SEED}-{component}") and the first floor(n/2) become "heldout", the rest "dev".
Eval-set v2 (2026-09-29) expanded every agent component (MRM-002..005) from 6/6/6/4 to 20 portfolio
variants each (full book + 19 seeded 10-name subsets; the first 5 subsets are the v1 ones), giving 10
held-out items per component. Agent splits were regenerated by the same rule; the 47 RAG items and their
split are unchanged.

Item fields
-----------
id, component (MRM-00x), split, grading ("exact_fact" | "grounded"),
question (RAG) or variant (agents: portfolio subset spec),
required_values [{"value": float, "label": str}], required_terms [str],
reference_answer (human-readable, derived from the same values).
"""

from __future__ import annotations

import json
import os
import random
from typing import List

from src.utils import metrics
from src.utils.data import DATA_DIR, load_earnings, load_macro, load_market_data, load_portfolio

DATASET_PATH = os.path.join(DATA_DIR, "eval", "fintech_eval.jsonl")
SPLIT_SEED = 7
SELECT_SEED = 11


def _fact(qid, question, values=(), terms=(), reference=""):
    return {"id": qid, "component": "MRM-001", "grading": "exact_fact", "question": question,
            "required_values": [{"value": v, "label": lab} for v, lab in values],
            "required_terms": list(terms), "reference_answer": reference}


def _qual(qid, question):
    return {"id": qid, "component": "MRM-001", "grading": "grounded", "question": question,
            "required_values": [], "required_terms": [], "reference_answer": "(graded for groundedness only)"}


def rag_items() -> List[dict]:
    pf = load_portfolio()
    pos = pf["positions"]
    k = metrics.portfolio_kpis(pf)
    rng = random.Random(SELECT_SEED)
    tickers = sorted(p["ticker"] for p in pos)
    by_t = {p["ticker"]: p for p in pos}
    items = []

    lp = k["largest_position"]
    items.append(_fact("rag-largest-position", "Which position has the largest market value?",
                       terms=[lp["ticker"]], reference=f"{lp['ticker']} ({lp['market_value']})"))
    items.append(_fact("rag-aum", "What is the fund's total AUM?", values=[(k["aum"], "aum")],
                       reference=f"{k['aum']}"))
    items.append(_fact("rag-n-positions", "How many positions does the fund hold?",
                       values=[(k["n_positions"], "n_positions")], reference=str(k["n_positions"])))
    items.append(_fact("rag-weighted-beta", "What is the portfolio's value-weighted beta?",
                       values=[(k["weighted_beta"], "weighted_beta")], reference=str(k["weighted_beta"])))
    items.append(_fact("rag-total-pnl", "What is the portfolio's total unrealized P&L?",
                       values=[(k["total_unrealized_pnl"], "total_unrealized_pnl")],
                       reference=str(k["total_unrealized_pnl"])))
    for sector, s in k["sector_weights"].items():
        items.append(_fact(f"rag-sector-weight-{sector.lower().replace(' ', '-')}",
                           f"What is the portfolio weight of the {sector} sector?",
                           values=[(s["weight_pct"], "weight_pct")], reference=f"{s['weight_pct']}%"))
    for t in rng.sample(tickers, 5):
        p = by_t[t]
        items.append(_fact(f"rag-pnl-{t}", f"What is the unrealized P&L of the {t} position?",
                           values=[(p["unrealized_pnl"], "unrealized_pnl")], reference=str(p["unrealized_pnl"])))
    for t in rng.sample(tickers, 5):
        p = by_t[t]
        items.append(_fact(f"rag-beta-{t}", f"What is the beta of {t}?",
                           values=[(p["beta"], "beta")], reference=str(p["beta"])))
    for t in rng.sample(tickers, 2):
        p = by_t[t]
        items.append(_fact(f"rag-mv-{t}", f"What is the market value of our {t} holding?",
                           values=[(p["market_value"], "market_value")], reference=str(p["market_value"])))
    items.append(_fact("rag-high-beta", "Which positions have a beta above 1.5?",
                       terms=k["high_beta_positions"], reference=", ".join(k["high_beta_positions"])))
    losers = [x["ticker"] for x in k["loss_positions"]]
    items.append(_fact("rag-loss-positions", "Which positions currently have unrealized losses?",
                       terms=losers, reference=", ".join(losers)))

    v95 = metrics.calculate_portfolio_var(pos, 0.95)
    v99 = metrics.calculate_portfolio_var(pos, 0.99)
    cv = metrics.calculate_portfolio_cvar(pos, 0.95)
    st = metrics.run_stress_tests(pos)
    items.append(_fact("rag-var95", "What is the portfolio's 1-day 95% parametric VaR?",
                       values=[(abs(v95["portfolio_var_1d"]), "var_1d_95")], reference=str(abs(v95["portfolio_var_1d"]))))
    items.append(_fact("rag-var99", "What is the portfolio's 1-day 99% VaR?",
                       values=[(abs(v99["portfolio_var_1d"]), "var_1d_99")], reference=str(abs(v99["portfolio_var_1d"]))))
    items.append(_fact("rag-cvar", "What is the Monte Carlo 1-day CVaR (expected shortfall) at 95%?",
                       values=[(abs(cv["cvar_1d"]), "cvar_1d")], reference=str(abs(cv["cvar_1d"]))))
    items.append(_fact("rag-tail-ratio", "What is the CVaR to VaR tail ratio?",
                       values=[(cv["tail_ratio"], "tail_ratio")], reference=str(cv["tail_ratio"])))
    items.append(_fact("rag-worst-stress", "Which stress scenario causes the largest loss, and what is the loss in percent?",
                       values=[(st["summary"]["worst_case_pnl_pct"], "worst_case_pnl_pct")],
                       terms=[st["summary"]["worst_case_scenario"].split()[0]],
                       reference=f"{st['summary']['worst_case_scenario']} {st['summary']['worst_case_pnl_pct']}%"))
    top = max((metrics.score_position_risk(p) for p in pos), key=lambda r: r["risk_score"])
    items.append(_fact("rag-top-risk", "Which position has the highest risk score, and what is the score?",
                       values=[(top["risk_score"], "risk_score")], terms=[top["ticker"]],
                       reference=f"{top['ticker']} {top['risk_score']}/100"))
    conc = metrics.concentration_check(pf)
    b = conc["sector_breaches"][0] if conc["sector_breaches"] else None
    if b:
        items.append(_fact("rag-sector-breach", "Which sector is above the sector concentration limit, and at what weight?",
                           values=[(b["weight_pct"], "weight_pct")], terms=[b["sector"]],
                           reference=f"{b['sector']} {b['weight_pct']}%"))

    macro = sorted(load_macro(), key=lambda m: m["date"])[-1]
    for key, qtxt in (("VIX", "What was the latest VIX reading?"),
                      ("Federal Funds Rate", "What is the latest Federal Funds Rate in the macro data?"),
                      ("CPI YoY", "What was the latest CPI YoY inflation reading?")):
        items.append(_fact(f"rag-macro-{key.lower().replace(' ', '-')}", qtxt,
                           values=[(macro[key], key)], reference=f"{macro[key]} ({macro['date']})"))

    earnings = sorted(load_earnings(), key=lambda e: (e["ticker"], e["date"]))
    for e in rng.sample(earnings, 4):
        items.append(_fact(f"rag-revenue-{e['ticker']}-{e['quarter'].replace(' ', '')}",
                           f"What revenue did {e['ticker']} report for {e['quarter']}?",
                           values=[(e["revenue_actual"] * 1e9, "revenue_actual_usd")],
                           reference=f"${e['revenue_actual']}B"))
    for e in rng.sample(earnings, 2):
        items.append(_fact(f"rag-eps-{e['ticker']}-{e['quarter'].replace(' ', '')}",
                           f"What EPS did {e['ticker']} report for {e['quarter']}?",
                           values=[(e["eps_actual"], "eps_actual")], reference=f"${e['eps_actual']}"))
    sig = metrics.technical_signals(load_market_data(), tickers)
    for t in rng.sample(tickers, 2):
        items.append(_fact(f"rag-rsi-{t}", f"What is the latest RSI-14 for {t}?",
                           values=[(sig[t]["rsi_14"], "rsi_14")], reference=str(sig[t]["rsi_14"])))

    items += [
        _qual("rag-q-macro", "Summarize the latest macro environment."),
        _qual("rag-q-risks", "What are the main risks in this portfolio?"),
        _qual("rag-q-concentration", "How concentrated is the portfolio?"),
        _qual("rag-q-cvar", "Explain what the CVaR figure means for this portfolio."),
        _qual(f"rag-q-earnings-{tickers[0]}", f"Summarize {tickers[0]}'s most recent earnings call."),
    ]
    return items


AGENT_COMPONENTS = ("MRM-002", "MRM-003", "MRM-004", "MRM-005")
N_AGENT_VARIANTS = 20  # -> 10 held-out items per agent component after the 50/50 split


def portfolio_variants(n: int = N_AGENT_VARIANTS) -> List[dict]:
    """The full book plus seeded 10-name subsets (the first 5 subsets match eval-set v1)."""
    tickers = sorted(p["ticker"] for p in load_portfolio()["positions"])
    rng = random.Random(SELECT_SEED + 1)
    variants = [{"name": "full", "tickers": tickers}]
    seen = {tuple(tickers)}
    i = 0
    while len(variants) < n:
        sub = sorted(rng.sample(tickers, 10))
        i += 1
        if tuple(sub) in seen:
            continue
        seen.add(tuple(sub))
        variants.append({"name": f"subset{i}", "tickers": sub})
    return variants


def agent_items() -> List[dict]:
    """Every agent component (and the orchestrator) is evaluated on the same 20 portfolio variants."""
    variants = portfolio_variants()
    items = []
    for comp in AGENT_COMPONENTS:
        for v in variants:
            item = {"id": f"{comp.lower()}-{v['name']}", "component": comp, "grading": "grounded",
                    "variant": v, "required_values": [], "required_terms": [],
                    "reference_answer": "(graded for groundedness + numeric consistency against its inputs)"}
            items.append(item)
    return items


def variant_portfolio(variant: dict) -> dict:
    """Portfolio restricted to the variant's tickers with weights/AUM recomputed."""
    pf = load_portfolio()
    pos = [dict(p) for p in pf["positions"] if p["ticker"] in set(variant["tickers"])]
    total = sum(p["market_value"] for p in pos)
    for p in pos:
        p["weight_pct"] = round(p["market_value"] / total * 100, 2)
    return {**pf, "positions": pos, "aum": round(total, 2)}


def assign_splits(items: List[dict]) -> List[dict]:
    """Deterministic 50/50 dev/heldout split within each component."""
    out = []
    for comp in sorted({i["component"] for i in items}):
        group = sorted((i for i in items if i["component"] == comp), key=lambda i: i["id"])
        rng = random.Random(f"{SPLIT_SEED}-{comp}")
        order = list(range(len(group)))
        rng.shuffle(order)
        heldout = set(order[: len(group) // 2])
        for idx, item in enumerate(group):
            out.append({**item, "split": "heldout" if idx in heldout else "dev"})
    return out


def build_dataset() -> List[dict]:
    return assign_splits(rag_items() + agent_items())


def write_dataset(path: str = DATASET_PATH) -> List[dict]:
    items = build_dataset()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        for it in items:
            f.write(json.dumps(it, sort_keys=True) + "\n")
    return items


def load_dataset(path: str = DATASET_PATH) -> List[dict]:
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]
